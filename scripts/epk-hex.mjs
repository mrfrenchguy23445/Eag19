import fs from "node:fs";
import zlib from "node:zlib";
const buf = fs.readFileSync("target_teavm_wasm_gc/javascript/assets.epk");
const h = (n, o = 0) => buf.subarray(o, o + n).toString("hex").replace(/(..)/g, "$1 ").trim();
console.log("head48:", h(48));
console.log("tail16:", h(16, buf.length - 16));
let off = 8;
const vl = buf[off++];
const ver = buf.subarray(off, off + vl).toString();
off += vl;
const fnl = buf[off++];
const fname = buf.subarray(off, off + fnl).toString();
off += fnl;
const cmt = buf.readUInt16BE(off); off += 2; off += cmt;
off += 8;
const numFiles = buf.readUInt32BE(off); off += 4;
const comp = String.fromCharCode(buf[off]); off += 1;
console.log({ ver, fname, cmt, numFiles, comp, off, gzipHead: h(8, off) });
const raw = zlib.gunzipSync(buf.subarray(off, buf.length - 8));
console.log("raw head 32:", raw.subarray(0, 32).toString("hex"));
console.log("raw start ASCII inches:", JSON.stringify(raw.subarray(0, 40).toString("latin1")));
